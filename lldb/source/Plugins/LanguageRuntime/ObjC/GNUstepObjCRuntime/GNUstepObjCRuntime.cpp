bool GNUstepObjCRuntime::CalculateHasNewLiteralsAndIndexing() {
  if (!m_process) 
    return false;
    
  Log *log = GetLog(LLDBLog::Language);
  Target &target = m_process->GetTarget();
  
  // Check for subscripting method presence - this is the most reliable indicator
  SymbolContextList sc_list;
  
  // Primary check: NSDictionary subscripting (most reliable indicator)
  target.GetImages().FindSymbolsWithNameAndType(
      ConstString("-[NSDictionary objectForKeyedSubscript:]"),
      eSymbolTypeCode, sc_list);
  
  if (!sc_list.IsEmpty()) {
    LLDB_LOG(log, "GNUstep: Found NSDictionary subscripting support");
    return true;
  }
  
  // Fallback: NSArray subscripting
  sc_list.Clear();
  target.GetImages().FindSymbolsWithNameAndType(
      ConstString("-[NSArray objectAtIndexedSubscript:]"),
      eSymbolTypeCode, sc_list);
      
  if (!sc_list.IsEmpty()) {
    LLDB_LOG(log, "GNUstep: Found NSArray subscripting support");
    return true;
  }
  
  // Check for GNUstep Base version symbols as indicator
  sc_list.Clear();
  target.GetImages().FindSymbolsWithNameAndType(
      ConstString("gnustep_base_version"), 
      eSymbolTypeData, sc_list);
      
  if (!sc_list.IsEmpty()) {
    // Assume modern GNUstep Base has subscripting (Base 1.24+)
    LLDB_LOG(log, "GNUstep: Found gnustep_base_version, assuming subscripting support");
    return true;
  }
  
  // Check for NSConstantString class as fallback indicator
  sc_list.Clear(); 
  target.GetImages().FindSymbolsWithNameAndType(
      ConstString("NSConstantString"),
      eSymbolTypeObjCClass, sc_list);
      
  if (!sc_list.IsEmpty()) {
    // If we have NSConstantString, we likely have modern GNUstep Base
    LLDB_LOG(log, "GNUstep: Found NSConstantString class, likely modern GNUstep Base");
    return true;
  }
  
  LLDB_LOG(log, "GNUstep: No subscripting support detected");
  return false;
}

llvm::Expected<std::unique_ptr<UtilityFunction>>
GNUstepObjCRuntime::CreateObjectChecker(std::string name, ExecutionContext &exe_ctx) {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::CreateObjectChecker called with name: {0}", name);
  
  // Generate the code for the object checker function
  // This function checks if an Objective-C object is valid and optionally
  // whether it responds to a given selector.
  // If the object is invalid or doesn't respond to the selector, it causes
  // a controlled crash by dereferencing a null pointer, which can be caught
  // by LLDB to handle conditional breakpoints.
  // The function signature is:
  // void <name>(void *obj, void *selector);
  // where 'obj' is the Objective-C object pointer and 'selector' is the SELectors.
  // If 'obj' is nil (0), it is considered valid. If 'selector' is nil (0),
  // the function only checks if 'obj' is valid.
  char check_function_code[2048];
  
  // Check if debugger-specific functions are available (Apple LLDB extensions)
  static const ConstString g_gdb_object_getClass("gdb_object_getClass");
  bool has_gdb_object_getClass = false;
  
  // Check for gdb_object_getClass symbol (LLDB-specific debugging function)
  if (Process *process = exe_ctx.GetProcessPtr()) {
    Target &target = process->GetTarget();
    const ModuleList &module_list = target.GetImages();
    for (size_t i = 0; i < module_list.GetSize(); ++i) {
      ModuleSP module_sp = module_list.GetModuleAtIndex(i);
      if (module_sp) {
        if (const Symbol *symbol = module_sp->FindFirstSymbolWithNameAndType(
                g_gdb_object_getClass, lldb::eSymbolTypeCode)) {
          if (symbol->ValueIsAddress() || symbol->GetAddressRef().IsValid()) {
            has_gdb_object_getClass = true;
            break;
          }
        }
      }
    }
  }
  
  int len;
  if (has_gdb_object_getClass) {
    // Use Apple's gdb_object_getClass approach if available
    len = ::snprintf(check_function_code, sizeof(check_function_code), R"(
extern "C" void *gdb_object_getClass(void *);
extern "C" int printf(const char *format, ...);

extern "C" void
%s(void *$__lldb_arg_obj, void *$__lldb_arg_selector) {
  // nil object is always OK for Objective-C
  if ($__lldb_arg_obj == (void *)0)
    return;
  
  // Check if object has a valid class using gdb_object_getClass (LLDB-specific function)
  if (!gdb_object_getClass($__lldb_arg_obj)) {
    // Invalid object - cause controlled crash for conditional breakpoints
    *((volatile int *)0) = 'ocgc';
  } else if ($__lldb_arg_selector != (void *)0) {
    // Use Objective-C respondsToSelector: syntax
    signed char $responds = (signed char)
        [(id)$__lldb_arg_obj respondsToSelector:
            (void *) $__lldb_arg_selector];
    if ($responds == (signed char) 0) {
      // Object doesn't respond to selector - cause controlled crash
      *((volatile int *)0) = 'ocgc';
    }
  }
})",
                     name.c_str());
  } else {
    // Fallback for GNUstep: simpler object checker without debugger-specific functions
    // Just validate that respondsToSelector works without class validation
    len = ::snprintf(check_function_code, sizeof(check_function_code), R"(
extern "C" int printf(const char *format, ...);

extern "C" void
%s(void *$__lldb_arg_obj, void *$__lldb_arg_selector) {
  // nil object is always OK for Objective-C
  if ($__lldb_arg_obj == (void *)0)
    return;
  
  // For GNUstep, skip complex object validation and just check selector response
  // This avoids linkage issues with debugger-specific functions
  if ($__lldb_arg_selector != (void *)0) {
    // Use Objective-C respondsToSelector: syntax - let runtime handle validation
    signed char $responds = (signed char)
        [(id)$__lldb_arg_obj respondsToSelector:
            (void *) $__lldb_arg_selector];
    if ($responds == (signed char) 0) {
      // Object doesn't respond to selector - cause controlled crash
      *((volatile int *)0) = 'ocgc';
    }
  }
  // If we get here, validation passed - continue normally
})",
                     name.c_str());
  }

  if (len >= (int)sizeof(check_function_code)) {
    LLDB_LOG(log, "GNUstepObjCRuntime::CreateObjectChecker: Generated code too long");
    return llvm::createStringError(llvm::inconvertibleErrorCode(), 
                                   "Object checker code generation failed - code too long");
  }

  LLDB_LOG(log, "GNUstepObjCRuntime::CreateObjectChecker: Generated object checker (gdb_object_getClass available: {0}):\n{1}", 
           has_gdb_object_getClass, check_function_code);

  // Create the utility function that LLDB can execute
  return GetTargetRef().CreateUtilityFunction(check_function_code, name,
                                              eLanguageTypeC, exe_ctx);
}

llvm::Expected<std::unique_ptr<UtilityFunction>>
GNUstepObjCRuntime::CreateSubscriptUtilityFunctions(ExecutionContext &exe_ctx) {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::CreateSubscriptUtilityFunctions called");
  
  // Create utility functions that implement modern subscript syntax by forwarding to older methods
  // This enables po fruits[0] and po dict[@"key"] to work by translating to [fruits objectAtIndex:0]
  const char *subscript_functions = R"(
extern "C" void *objc_lookup_class(const char *);
extern "C" void *class_getMethodImplementation(void *cls, void *sel);
extern "C" void *sel_getUid(const char *);
extern "C" void *objc_msgSend(void *self, void *sel, ...);

// Implement objectAtIndexedSubscript: by calling objectAtIndex:
extern "C" void* 
__lldb_objc_objectAtIndexedSubscript(void *self, void *_cmd, long idx) {
  if (!self) return (void *)0;
  
  // Get the selector for objectAtIndex:
  void *sel_objectAtIndex = sel_getUid("objectAtIndex:");
  if (!sel_objectAtIndex) return (void *)0;
  
  // Forward the call to the older objectAtIndex: method
  return objc_msgSend(self, sel_objectAtIndex, idx);
}

// Implement objectForKeyedSubscript: by calling objectForKey:
extern "C" void*
__lldb_objc_objectForKeyedSubscript(void *self, void *_cmd, void *key) {
  if (!self) return (void *)0;
  
  // Get the selector for objectForKey:
  void *sel_objectForKey = sel_getUid("objectForKey:");
  if (!sel_objectForKey) return (void *)0;
  
  // Forward the call to the older objectForKey: method
  return objc_msgSend(self, sel_objectForKey, key);
}

// Entry point function for the utility
void __lldb_objc_subscript_utilities() {
  // This function exists only to satisfy the utility function loader
  // The actual work is done by the functions above
}
)";

  LLDB_LOG(log, "GNUstepObjCRuntime::CreateSubscriptUtilityFunctions: Generated subscript utility functions");

  // Create the utility function that LLDB can execute
  return GetTargetRef().CreateUtilityFunction(subscript_functions, "__lldb_objc_subscript_utilities",
                                              eLanguageTypeC, exe_ctx);
}

void GNUstepObjCRuntime::UpdateISAToDescriptorMapIfNeeded() {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::UpdateISAToDescriptorMapIfNeeded called");
  
  if (!m_runtime_api_up) {
    LLDB_LOG(log, "No runtime API available for ISA map update");
    return;
  }
  
  // Get all Foundation classes from the runtime
  auto foundation_classes = m_runtime_api_up->GetAllFoundationClasses();
  if (!foundation_classes) {
    // Consume the error and continue - this isn't critical
    llvm::consumeError(foundation_classes.takeError());
    LLDB_LOG(log, "Could not enumerate Foundation classes for ISA map");
    return;
  }
  
  LLDB_LOG(log, "Updating ISA map with {0} Foundation classes", 
           foundation_classes->size());
  
  // Add each class to the ISA-to-descriptor map
  for (const auto &class_info : *foundation_classes) {
    lldb::addr_t class_addr = reinterpret_cast<lldb::addr_t>(class_info.class_ptr);
    if (class_addr != LLDB_INVALID_ADDRESS && class_addr != 0) {
      // Check if we already have this ISA in our map
      ClassDescriptorSP existing_descriptor = ObjCLanguageRuntime::GetClassDescriptorFromISA(class_addr);
      if (!existing_descriptor) {
        // Create a new descriptor for this class
        ClassDescriptorSP new_descriptor = ClassDescriptorSP(
            new GNUstepClassDescriptor(*this, class_addr, class_info.name.c_str()));
        
        if (new_descriptor && new_descriptor->IsValid()) {
          AddClass(class_addr, new_descriptor);
          LLDB_LOG(log, "Added ISA mapping: 0x{0:x} -> {1}", 
                   class_addr, class_info.name);
        }
      }
    }
  }
  
  // Also update any custom classes we've encountered during runtime introspection
  if (m_introspector_up) {
    // The introspector may have cached ISA-to-name mappings we can use
    // This is a future enhancement point for custom class discovery
  }
}

ObjCLanguageRuntime::ClassDescriptorSP
GNUstepObjCRuntime::GetClassDescriptorFromISA(ObjCISA isa) {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::GetClassDescriptorFromISA called with ISA {0:x}", isa);
  
  if (!isa)
    return ClassDescriptorSP();
  
  // First check the base class cache
  UpdateISAToDescriptorMap();
  ClassDescriptorSP descriptor_sp = ObjCLanguageRuntime::GetClassDescriptorFromISA(isa);
  if (descriptor_sp)
    return descriptor_sp;
  
  // If not in cache, create a new GNUstepClassDescriptor
  descriptor_sp = ClassDescriptorSP(new GNUstepClassDescriptor(*this, isa, nullptr));
  
  // Add to cache if valid
  if (descriptor_sp && descriptor_sp->IsValid()) {
    AddClass(isa, descriptor_sp);
    return descriptor_sp;
  }
  
  return ClassDescriptorSP();
}

ObjCLanguageRuntime::ClassDescriptorSP
GNUstepObjCRuntime::GetClassDescriptor(ValueObject &valobj) {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::GetClassDescriptor called for ValueObject");
  
  // Handle base class case (like Apple's implementation)
  if (valobj.IsBaseClass()) {
    ValueObject *parent = valobj.GetParent();
    if (parent && parent != &valobj) {
      ClassDescriptorSP parent_descriptor_sp = GetClassDescriptor(*parent);
      if (parent_descriptor_sp)
        return parent_descriptor_sp->GetSuperclass();
    }
    return nullptr;
  }
  
  // Get the ISA pointer from the object
  addr_t isa_pointer = valobj.GetPointerValue();
  if (!isa_pointer)
    return ClassDescriptorSP();
  
  // Read the ISA from the object's first field
  ExecutionContext exe_ctx(valobj.GetExecutionContextRef());
  Process *process = exe_ctx.GetProcessPtr();
  if (!process)
    return ClassDescriptorSP();
  
  Status error;
  ObjCISA isa = process->ReadPointerFromMemory(isa_pointer, error);
  if (error.Fail())
    return ClassDescriptorSP();
  
  return GetClassDescriptorFromISA(isa);
}

ObjCLanguageRuntime::ClassDescriptorSP
GNUstepObjCRuntime::GetClassDescriptorFromClassName(ConstString class_name) {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::GetClassDescriptorFromClassName called for class: {0}", class_name.GetCString());
  
  if (!class_name)
    return ClassDescriptorSP();
  
  // First check if it's already in the cache using base class method
  ClassDescriptorSP cached_descriptor = ObjCLanguageRuntime::GetClassDescriptorFromClassName(class_name);
  if (cached_descriptor) {
    LLDB_LOG(log, "Class '{0}' found in cache", class_name.GetCString());
    return cached_descriptor;
  }
  
  // Use our runtime function to get the class address
  lldb::addr_t class_addr = CallRuntimeFunction("objc_getClass", class_name.GetCString());
  if (class_addr == LLDB_INVALID_ADDRESS || class_addr == 0) {
    LLDB_LOG(log, "objc_getClass returned invalid address for class: {0}", class_name.GetCString());
    return ClassDescriptorSP();
  }
  
  LLDB_LOG(log, "objc_getClass resolved class '{0}' to address 0x{1:x}", class_name.GetCString(), class_addr);
  
  // Create a class descriptor from the ISA (class address)
  ClassDescriptorSP descriptor_sp = GetClassDescriptorFromISA(class_addr);
  if (descriptor_sp && descriptor_sp->IsValid()) {
    LLDB_LOG(log, "Successfully created class descriptor for '{0}'", class_name.GetCString());
    return descriptor_sp;
  }
  
  LLDB_LOG(log, "Failed to create valid class descriptor for '{0}'", class_name.GetCString());
  return ClassDescriptorSP();
}

void GNUstepObjCRuntime::InitializeRuntimeAPI() {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::InitializeRuntimeAPI - Initializing runtime API");
  
  if (!m_process) {
    LLDB_LOG(log, "No process available for runtime API");
    return;
  }
  
  auto api_or_error = GNUstepRuntimeV2API::Create(m_process);
  if (api_or_error) {
    m_runtime_api_up = std::move(*api_or_error);
    LLDB_LOG(log, "Runtime V2 API initialized successfully");
    
    // Log runtime version
    if (m_runtime_api_up) {
      std::string version = m_runtime_api_up->GetRuntimeVersion();
      LLDB_LOG(log, "Runtime version: {0}", version);
      
      // Enumerate and log Foundation classes
      auto foundation_classes = m_runtime_api_up->GetAllFoundationClasses();
      if (foundation_classes) {
        LLDB_LOG(log, "Found {0} Foundation classes", foundation_classes->size());
        
        // Log first few Foundation classes for debugging
        size_t count = 0;
        for (const auto &cls : *foundation_classes) {
          if (count++ < 10) {
            LLDB_LOG(log, "  Foundation class: {0} (superclass: {1})", 
                     cls.name, cls.superclass_name);
          }
        }
      } else {
        // Consume the error from GetAllFoundationClasses
        llvm::consumeError(foundation_classes.takeError());
        // This is not critical - formatters will still work through other mechanisms
        LLDB_LOG(log, "[GNUstepObjC] Note: Runtime class enumeration not available, using fallback mechanisms");
      }
      
      // ENHANCED FIX: Install subscript method mapping for GNUstep
      // Instead of injecting utility functions (which can crash), we map modern subscript
      // methods to traditional GNUstep methods using expression rewriting
      InstallSubscriptMethodMapping();
    }
  } else {
    llvm::handleAllErrors(api_or_error.takeError(),
                          [&](const llvm::StringError &SE) {
                            LLDB_LOG(log, "Failed to initialize runtime API: {0}", 
                                     SE.getMessage());
                          });
  }
}

void GNUstepObjCRuntime::RegisterFormatters() {
  if (m_formatters_registered) {
    return;
  }
    
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  LLDB_LOG(log, "GNUstepObjCRuntime::RegisterFormatters - Registering GNUstep formatters");
  
  // Disable Apple's ObjC formatters to prevent conflicts
  // This is necessary because both Apple and GNUstep register formatters for the same types
  TypeCategoryImplSP objc_category_sp;
  if (DataVisualization::Categories::GetCategory(ConstString("objc"), objc_category_sp)) {
    DataVisualization::Categories::Disable(ConstString("objc"));
    LLDB_LOG(log, "Disabled Apple ObjC formatters to prevent conflicts");
  }
  
  // Get or create the GNUstep type category
  TypeCategoryImplSP category_sp;
  if (!DataVisualization::Categories::GetCategory(ConstString("gnustep"), 
                                                  category_sp, true)) {
    LLDB_LOG(log, "Failed to get/create GNUstep category");
    return;
  }
  
  if (!category_sp) {
    LLDB_LOG(log, "Got null category pointer");
    return;
  }
  
  // Register our formatters
  GNUstepFormattersRegistry::RegisterFormatters(*category_sp);
  
  // Enable the category with higher priority than default
  DataVisualization::Categories::Enable(ConstString("gnustep"), 
                                        TypeCategoryMap::Default);
  
  m_formatters_registered = true;
  LLDB_LOG(log, "GNUstep formatters registered and category enabled");
}

