void GNUstepObjCRuntime::InstallSubscriptMethodMapping() {
  Log *log = GetLog(LLDBLog::Process | LLDBLog::Types);
  
  // Check if NSArray responds to objectAtIndex:
  // If it does, we can safely map subscript calls to traditional methods
  ExecutionContext exe_ctx(m_process);
  
  // Enhanced check using our runtime API for better reliability
  if (m_runtime_api_up) {
    bool array_supports_index = m_runtime_api_up->ClassRespondsToSelector("NSArray", "objectAtIndex:");
    bool dict_supports_key = m_runtime_api_up->ClassRespondsToSelector("NSDictionary", "objectForKey:");
    
    if (array_supports_index && dict_supports_key) {
      LLDB_LOG(log, "GNUstep classes support traditional methods via runtime API, subscript mapping enabled");
      m_subscript_mapping_enabled = true;
      
      // Install expression evaluation hooks for modern subscript syntax
      InstallExpressionEvaluationHooks();
      
      return;
    } else {
      LLDB_LOG(log, "Runtime API check failed: NSArray->objectAtIndex: %s, NSDictionary->objectForKey: %s",
               array_supports_index ? "YES" : "NO", dict_supports_key ? "YES" : "NO");
    }
  }
  
  // Fallback to expression evaluation if runtime API is not available
  std::string check_expr = R"(
    (BOOL)[(Class)objc_getClass("NSArray") respondsToSelector:@selector(objectAtIndex:)] &&
    (BOOL)[(Class)objc_getClass("NSDictionary") respondsToSelector:@selector(objectForKey:)]
  )";
  
  EvaluateExpressionOptions options = MakeSafeExprOpts();
  
  ValueObjectSP result_sp;
  Status error;
  UserExpression::Evaluate(exe_ctx, options, check_expr.c_str(), 
                           "", result_sp, nullptr);
  
  if (error.Success() && result_sp && result_sp->GetValueAsUnsigned(0)) {
    LLDB_LOG(log, "GNUstep classes support traditional methods via expression evaluation, subscript mapping enabled");
    m_subscript_mapping_enabled = true;
    
    // Install expression evaluation hooks for modern subscript syntax
    InstallExpressionEvaluationHooks();
  } else {
    LLDB_LOG(log, "Could not verify GNUstep method support, subscript mapping disabled");
    m_subscript_mapping_enabled = false;
  }
}

void GNUstepObjCRuntime::InstallExpressionEvaluationHooks() {
  Log *log = GetLog(LLDBLog::Language | LLDBLog::Types);
  LLDB_LOG(log, "Installing expression evaluation hooks for GNUstep ObjC runtime");
  
  // Prevent multiple installations
  if (m_expression_hooks_installed) {
    LLDB_LOG(log, "Expression evaluation hooks already installed");
    return;
  }
  
  // 1) Resolve and cache canonical ObjC runtime symbols from libobjc2
  ResolveAndCacheRuntimeSymbols();
  
  // Early-out if we can't resolve ANY runtime symbols yet - be more conservative
  // Research Agent Plan: Only require minimal symbol availability for activation
  if (m_objc_msgSend_addr == LLDB_INVALID_ADDRESS &&
      m_objc_getClass_addr == LLDB_INVALID_ADDRESS &&
      m_sel_getUid_addr == LLDB_INVALID_ADDRESS) {
    LLDB_LOG(log, "No core runtime symbols available yet, deferring installation");
    return;
  }
  
  // 2) Ensure CFStringCreateWithBytes is available (real or fallback) 
  EnsureCFStringCreateWithBytes();
  
  // Removed hardcoded utility functions - IRForTarget handles all expression evaluation
  // Array/dictionary literal support, function injection, shims, and diagnostics
  // are now provided dynamically through runtime introspection
  
  // IRForTarget with objc_getClass dynamic calls now handles all expression evaluation needs
  LLDB_LOG(log, "[GNUstep] Expression evaluation relies on IRForTarget with runtime introspection");
  
  m_expression_hooks_installed = true;
  LLDB_LOG(log, "[GNUstep] Expression evaluation hooks installed successfully");
}

void GNUstepObjCRuntime::ResolveAndCacheRuntimeSymbols() {
  // Phase B: Thread-safe once-only symbol resolution
  std::call_once(m_symbol_resolution_flag, [this]() {
    std::lock_guard<std::mutex> lock(m_symbol_mutex);
    
    Log *log = GetLog(LLDBLog::Language | LLDBLog::Types);
    LLDB_LOG(log, "Resolving GNUstep runtime symbols for expression evaluation (thread-safe)");
  
  Target &target = GetProcess()->GetTarget();
  const ModuleList &modules = target.GetImages();
  
  // Define the symbols we need for expression evaluation
  struct SymbolInfo {
    const char *name;
    const char *fallback_name;
    lldb::addr_t *cache_addr;
  };
  
  SymbolInfo symbols[] = {
    {"objc_msgSend", nullptr, &m_objc_msgSend_addr},
    {"objc_msgSend_stret", nullptr, &m_objc_msgSend_stret_addr},
    {"objc_msgSend_fpret", nullptr, &m_objc_msgSend_fpret_addr},
    {"objc_getClass", "objc_lookup_class", &m_objc_getClass_addr},
    {"sel_getUid", "sel_registerName", &m_sel_getUid_addr},
    {"object_getClass", nullptr, &m_object_getClass_addr},
    {"class_getMethodImplementation", nullptr, &m_class_getMethodImplementation_addr},
    {"class_addMethod", nullptr, &m_class_addMethod_addr},
    // Optional ARC helpers (non-fatal if not found)
    {"objc_retain", nullptr, &m_objc_retain_addr},
    {"objc_release", nullptr, &m_objc_release_addr},
    {"objc_autoreleaseReturnValue", nullptr, &m_objc_autoreleaseReturnValue_addr},
    {"objc_retainAutoreleasedReturnValue", nullptr, &m_objc_retainAutoreleasedReturnValue_addr},
    {nullptr, nullptr, nullptr}
  };
  
  // Search starting with GNUstep ObjC modules (libobjc-*.dll, libobjc2*)
  for (size_t i = 0; i < modules.GetSize(); ++i) {
    ModuleSP module_sp = modules.GetModuleAtIndex(i);
    if (!module_sp) continue;
    
    const char *module_name = module_sp->GetFileSpec().GetFilename().GetCString();
    if (!module_name) continue;
    
    // Check if this is a GNUstep ObjC runtime module
    bool is_objc_module = (strstr(module_name, "libobjc") ||
                          strstr(module_name, "objc2") ||
                          (strstr(module_name, "objc") && strstr(module_name, ".dll")));
    
    if (!is_objc_module) continue;
    
    LLDB_LOG(log, "Searching for runtime symbols in module: {0}", module_name);
    
    // Look for each symbol in this module
    for (int j = 0; symbols[j].name; j++) {
      if (*(symbols[j].cache_addr) != LLDB_INVALID_ADDRESS) continue; // Already found
      
      const Symbol *symbol = module_sp->FindFirstSymbolWithNameAndType(
          ConstString(symbols[j].name), eSymbolTypeCode);
      
      // Try fallback name if primary not found
      if (!symbol && symbols[j].fallback_name) {
        symbol = module_sp->FindFirstSymbolWithNameAndType(
            ConstString(symbols[j].fallback_name), eSymbolTypeCode);
      }
      
      if (symbol) {
        *(symbols[j].cache_addr) = symbol->GetLoadAddress(&target);
        LLDB_LOG(log, "Found {0} at 0x{1:x} in {2}", 
                symbols[j].name, *(symbols[j].cache_addr), module_name);
      }
    }
  }
  
  // Log what we found/didn't find
  int resolved_count = 0;
  for (int j = 0; symbols[j].name; j++) {
    if (*(symbols[j].cache_addr) != LLDB_INVALID_ADDRESS) {
      resolved_count++;
    } else {
      LLDB_LOG(log, "Warning: Could not resolve {0}", symbols[j].name);
    }
  }
  
  LLDB_LOG(log, "Resolved {0} out of {1} runtime symbols", resolved_count, 
           sizeof(symbols)/sizeof(symbols[0]) - 1);
  }); // End of std::call_once lambda
}

void GNUstepObjCRuntime::EnsureCFStringCreateWithBytes() {
  Log *log = GetLog(LLDBLog::Language | LLDBLog::Types);
  LLDB_LOG(log, "Ensuring CFStringCreateWithBytes is available");
  
  if (m_cfstring_create_addr != LLDB_INVALID_ADDRESS) {
    LLDB_LOG(log, "CFStringCreateWithBytes already available at 0x{0:x}", m_cfstring_create_addr);
    return;
  }
  
  // Ensure we have execution context before trying to install utility function
  if (!m_process || !m_process->IsAlive()) {
    LLDB_LOG(log, "Process not available for CFStringCreateWithBytes installation");
    return;
  }
  
  Target &target = GetProcess()->GetTarget();
  const ModuleList &modules = target.GetImages();
  
  // Research Agent Plan: Always try to find real function first, but always install fallback
  bool found_real_function = false;
  
  // First try to find the real CFStringCreateWithBytes in Foundation/CoreFoundation
  for (size_t i = 0; i < modules.GetSize(); ++i) {
    ModuleSP module_sp = modules.GetModuleAtIndex(i);
    if (!module_sp) continue;
    
    const char *module_name = module_sp->GetFileSpec().GetFilename().GetCString();
    if (!module_name) continue;
    
    // Check for Foundation/CoreFoundation modules with more comprehensive patterns
    bool is_foundation = (strstr(module_name, "gnustep-base") ||
                         strstr(module_name, "Foundation") ||
                         strstr(module_name, "CoreFoundation") ||
                         strstr(module_name, "libobjc") ||  // GNUstep libobjc might have it
                         strstr(module_name, "base"));      // Any base library
    
    if (!is_foundation) continue;
    
    const Symbol *symbol = module_sp->FindFirstSymbolWithNameAndType(
        ConstString("CFStringCreateWithBytes"), eSymbolTypeCode);
    
    if (symbol) {
      m_cfstring_create_addr = symbol->GetLoadAddress(&target);
      LLDB_LOG(log, "Found real CFStringCreateWithBytes at 0x{0:x} in {1}", 
               m_cfstring_create_addr, module_name);
      found_real_function = true;
      break;
    }
  }
  
  // Research Agent Plan: Always install fallback for robust IR rewriting support
  // Install fallback even when real function exists to ensure IR compatibility
  LLDB_LOG(log, "Installing CFStringCreateWithBytes fallback for comprehensive IR support");
  
  // Create fallback implementation with the correct function name for IR linking
  const char *cfstring_fallback = R"(
// GNUstep fallback for IR: CFStringCreateWithBytes
void *objc_getClass(const char*);
void *sel_getUid(const char*);
void *objc_msgSend(void*, void*, ...);

void *CFStringCreateWithBytes(void *alloc,
                             const unsigned char *bytes,
                             long numBytes,
                             unsigned long encoding,
                             unsigned char isExternalRepresentation)
{
  // Ignore allocator, encoding, isExternalRepresentation for simplicity
  void *nsstringClass = objc_getClass("NSString");
  if (!nsstringClass) return (void*)0;
  
  void *sel = sel_getUid("stringWithUTF8String:");
  if (!sel) return (void*)0;
  
  return objc_msgSend(nsstringClass, sel, (const char*)bytes);
}
)";

  // Setup execution context for utility function creation
  ExecutionContext exe_ctx(GetProcess());
  if (!exe_ctx.HasProcessScope()) {
    LLDB_LOG(log, "No valid execution context for CFString fallback installation");
    return;
  }
  
  LLDB_LOG(log, "Creating CFStringCreateWithBytes utility function...");
  
  // Create the utility function if not already created
  if (!m_cfstring_utility_fn) {
    auto utility_fn_or_err = target.CreateUtilityFunction(
        cfstring_fallback, "CFStringCreateWithBytes", eLanguageTypeC, exe_ctx);
    
    if (!utility_fn_or_err) {
      LLDB_LOG(log, "Failed to create CFStringCreateWithBytes fallback: {0}", 
               llvm::toString(utility_fn_or_err.takeError()));
      return;
    }
    
    m_cfstring_utility_fn = std::move(*utility_fn_or_err);
    LLDB_LOG(log, "CFStringCreateWithBytes utility function created successfully");
  }
  
  // Install the utility function
  LLDB_LOG(log, "Installing CFStringCreateWithBytes utility function...");
  DiagnosticManager diagnostic_manager;
  Status install_error;
  bool installation_succeeded = m_cfstring_utility_fn->Install(diagnostic_manager, exe_ctx);
  
  if (!installation_succeeded) {
    std::string diag_msg = diagnostic_manager.GetString();
    // "already installed" is actually a success case
    if (diag_msg.find("already installed") != std::string::npos) {
      LLDB_LOG(log, "CFStringCreateWithBytes utility function was already installed (this is OK)");
      installation_succeeded = true;
    } else {
      LLDB_LOG(log, "Failed to install CFStringCreateWithBytes fallback: {0}", diag_msg);
      return;
    }
  } else {
    LLDB_LOG(log, "CFStringCreateWithBytes utility function installed successfully");
  }
  
  // Get the real address of our installed fallback function
  // Try multiple approaches to find the installed function
  Target &tgt = exe_ctx.GetTargetRef();
  
  // Approach 1: Look for the symbol in all modules
  SymbolContextList sc_list;
  tgt.GetImages().FindSymbolsWithNameAndType(
      ConstString("CFStringCreateWithBytes"), eSymbolTypeCode, sc_list);
  
  LLDB_LOG(log, "Found {0} CFStringCreateWithBytes symbols after installation", sc_list.GetSize());
  
  // Approach 2: If not found, try to get address directly from utility function
  if (sc_list.GetSize() == 0 && m_cfstring_utility_fn) {
    lldb::addr_t utility_addr = m_cfstring_utility_fn->StartAddress();
    if (utility_addr != LLDB_INVALID_ADDRESS) {
      if (!found_real_function) {
        m_cfstring_create_addr = utility_addr;
        LLDB_LOG(log, "Got CFStringCreateWithBytes fallback address directly from utility function: 0x{0:x}", m_cfstring_create_addr);
      }
      return;
    }
  }
  
  // Approach 3: Standard symbol lookup
  if (sc_list.GetSize() > 0) {
    SymbolContext sc;
    sc_list.GetContextAtIndex(0, sc);
    if (sc.symbol) {
      // Research Agent Plan: Use fallback address if real function wasn't found
      if (!found_real_function) {
        m_cfstring_create_addr = sc.symbol->GetLoadAddress(&tgt);
        LLDB_LOG(log, "Installed CFStringCreateWithBytes fallback at 0x{0:x}", m_cfstring_create_addr);
      } else {
        LLDB_LOG(log, "CFStringCreateWithBytes fallback installed for IR robustness, using real function at 0x{0:x}", 
                 m_cfstring_create_addr);
      }
      return;
    }
  }
  
  LLDB_LOG(log, "Failed to get address of CFStringCreateWithBytes fallback after installation");
}

